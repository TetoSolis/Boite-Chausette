    private void bouttonSendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bouttonSendActionPerformed
        try {
            Engine.getUpdate(0);
        } catch (IOException | ParseException ex) {
            Logger.getLogger(Chat.class.getName()).log(Level.SEVERE, null, ex);
        }
        String text = champChat.getText();
        //ChaussetteClient plouf = new ChaussetteClient(Engine.getId(),Engine.getMdp(),"127.0.0.1", 4444);
        if (!text.isEmpty()) {
            try {
                Engine.send(Engine.Friends[numFrd].getId(),text);
            } catch (IOException ex) {
                Logger.getLogger(Chat.class.getName()).log(Level.SEVERE, null, ex);
            }
        } else {
            JOptionPane.showMessageDialog(null, "Texte vide...");
        }

            this.eraseMsg();
            this.printMsg(numFrd);

    }//GEN-LAST:event_bouttonSendActionPerformed

