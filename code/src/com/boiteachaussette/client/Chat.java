    public void eraseMsg(){
        jTextArea1.selectAll();
        jTextArea1.replaceSelection("");
    }
    public void printMsg(int indexFriend){
        Msg[] m = Engine.getMsg(numFrd);
        for (Msg m1 : m) {
            if (m1 != null) {
                jTextArea1.append("[" + m1.getFrom() + "] : "+ m1.getDatePretty() + " : " + m1.getContent() + "\n");
            }
        }
    }
    public void allDo(int indexFriend) throws IOException, SocketException, UnknownHostException, ParseException{
        display4Friends();
        eraseMsg();
        printMsg(indexFriend);
    }
